import { readFileSync, writeFileSync } from 'node:fs'

const { abi } = JSON.parse(readFileSync(new URL('../../out/Escrow.sol/Escrow.json', import.meta.url)))
writeFileSync(
  new URL('../src/lib/abi.ts', import.meta.url),
  `// Generated by \`npm run abi\` from the Foundry build. Do not edit.\nexport const escrowAbi = ${JSON.stringify(abi, null, 2)} as const\n`,
)
console.log(`wrote ${abi.length} ABI entries`)
